"""AMP training, early stopping and epoch-boundary resume.

Checkpoints are trusted local files generated by this project. Do not load
checkpoints downloaded from unknown sources with weights_only=False.
"""
from __future__ import annotations

import contextlib
import random
import time
from pathlib import Path

import numpy as np
import torch

from common.utils import atomic_torch_save, digest, read_json, synchronize, write_csv, write_json


def amp_context(device):
    return torch.autocast("cuda", dtype=torch.float16) if device.type == "cuda" else contextlib.nullcontext()


def rng_state():
    return {
        "python": random.getstate(), "numpy": np.random.get_state(),
        "torch": torch.get_rng_state(),
        "cuda": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
    }


def restore_rng(state):
    random.setstate(state["python"])
    np.random.set_state(state["numpy"])
    torch.set_rng_state(state["torch"].cpu())
    if state["cuda"] is not None and torch.cuda.is_available():
        torch.cuda.set_rng_state_all([s.cpu() for s in state["cuda"]])


def fit(model, train_loader, val_loader, step, settings, directory, device, identity, maximize=True):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    signature = digest({"identity": identity, "settings": settings})
    if (directory / "complete.json").exists():
        done = read_json(directory / "complete.json")
        if done["signature"] != signature:
            raise RuntimeError(f"Configuration/data changed in {directory}; use a new output directory.")
        model.load_state_dict(torch.load(directory / "best.pt", map_location=device, weights_only=True)["model"])
        print(f"Reuse completed training: {directory.name}", flush=True)
        return done
    optimizer = torch.optim.AdamW(
        [p for p in model.parameters() if p.requires_grad],
        lr=settings["lr"], weight_decay=settings.get("weight_decay", 1e-4),
    )
    scaler = torch.amp.GradScaler("cuda", enabled=device.type == "cuda")
    start, bad, best, best_epoch, elapsed, history = 0, 0, None, 0, 0.0, []
    if (directory / "last.pt").exists():
        state = torch.load(directory / "last.pt", map_location=device, weights_only=False)
        if state["signature"] != signature:
            raise RuntimeError(f"Resume signature mismatch: {directory}. Restore the config or use another output.")
        model.load_state_dict(state["model"])
        optimizer.load_state_dict(state["optimizer"])
        scaler.load_state_dict(state["scaler"])
        start, bad, best, best_epoch = state["epoch"], state["bad"], state["best"], state["best_epoch"]
        elapsed, history = state["elapsed"], state["history"]
        restore_rng(state["rng"])
        print(f"Resume {directory.name} after epoch {start}", flush=True)
    for epoch in range(start, settings["epochs"]):
        if bad >= settings["patience"]:
            break
        # Deterministic shuffle per epoch, including when resuming persistent workers.
        torch.manual_seed(identity["seed"] + epoch)
        synchronize(device)
        tick = time.perf_counter()
        results = {}
        for phase, batches in (("train", train_loader), ("val", val_loader)):
            model.train(phase == "train")
            sums, count, correct = 0.0, 0, 0
            with torch.set_grad_enabled(phase == "train"):
                for batch in batches:
                    if phase == "train":
                        optimizer.zero_grad(set_to_none=True)
                    with amp_context(device):
                        loss, n, hits = step(model, batch, device)
                    if not torch.isfinite(loss):
                        raise RuntimeError(f"Non-finite loss in {directory.name} epoch {epoch + 1}")
                    if phase == "train":
                        scaler.scale(loss).backward()
                        scaler.unscale_(optimizer)
                        torch.nn.utils.clip_grad_norm_(model.parameters(), settings.get("clip", 1.0))
                        scaler.step(optimizer)
                        scaler.update()
                    sums += float(loss.detach()) * n
                    count += n
                    correct += hits
            if count == 0:
                raise RuntimeError(f"Empty {phase} loader")
            results[f"{phase}_loss"] = sums / count
            results[f"{phase}_accuracy"] = correct / count
        synchronize(device)
        seconds = time.perf_counter() - tick
        elapsed += seconds
        row = {"epoch": epoch + 1, **results, "seconds": seconds}
        history.append(row)
        score = results["val_accuracy" if maximize else "val_loss"]
        improved = best is None or (score > best if maximize else score < best)
        if improved:
            best, best_epoch, bad = score, epoch + 1, 0
            atomic_torch_save({"model": model.state_dict(), "signature": signature,
                               "epoch": best_epoch, "identity": identity}, directory / "best.pt")
        else:
            bad += 1
        atomic_torch_save({
            "model": model.state_dict(), "optimizer": optimizer.state_dict(),
            "scaler": scaler.state_dict(), "epoch": epoch + 1, "bad": bad,
            "best": best, "best_epoch": best_epoch, "elapsed": elapsed,
            "history": history, "rng": rng_state(), "signature": signature,
        }, directory / "last.pt")
        write_csv(directory / "history.csv", history)
        print(f"{directory.name} epoch={epoch+1}/{settings['epochs']} "
              f"train_loss={results['train_loss']:.4f} val_loss={results['val_loss']:.4f} "
              f"train_acc={results['train_accuracy']:.4f} val_acc={results['val_accuracy']:.4f} "
              f"{seconds:.1f}s", flush=True)
    model.load_state_dict(torch.load(directory / "best.pt", map_location=device, weights_only=True)["model"])
    done = {
        "signature": signature, "identity": identity, "settings": settings,
        "best_epoch": best_epoch, "best_validation_score": best,
        "selection_metric": "val_accuracy" if maximize else "val_loss",
        "training_seconds": elapsed, "epochs_ran": len(history),
        "parameters": sum(p.numel() for p in model.parameters()),
        "trainable_parameters": sum(p.numel() for p in model.parameters() if p.requires_grad),
    }
    write_json(directory / "complete.json", done)
    plot_history(history, directory)
    return done


def plot_history(history, directory):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    for ax, name in zip(axes, ("loss", "accuracy")):
        for phase in ("train", "val"):
            ax.plot([r["epoch"] for r in history], [r[f"{phase}_{name}"] for r in history], label=phase)
        ax.set(xlabel="Epoch", ylabel=name)
        ax.legend()
    fig.tight_layout()
    fig.savefig(Path(directory) / "learning_curves.png", dpi=150)
    plt.close(fig)
